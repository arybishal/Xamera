package com.bishal.adaptivecamera.ui.theme

/**
 * Supported application theme modes.
 * - [SYSTEM]: Follows system dark/light configuration.
 * - [DARK]: High-contrast dark photography palette with cyan/amber accents.
 * - [LIGHT]: Clean, high-readability palette styled in signature Yellow, Black, and White.
 */
enum class AppThemeMode(val displayName: String) {
    SYSTEM("System Default"),
    DARK("Dark"),
    LIGHT("Light")
}
